/**
 * 把一个图标路径编译成可直接写进 CSS `background-image` 的 data URI。
 *
 * <h3>两个必须保留的坑（都踩过）</h3>
 *
 * 1. **颜色里的 `#` 必须编码成 `%23`**。
 *    `encodeURIComponent` 会把 `#` 编码掉；如果不编码，CSS 解析 `url()` 时
 *    会把 `#` 之后的内容当成 URL 的片段标识符（fragment）截断 ——
 *    结果是**图标完全不显示，而且控制台没有任何报错**，极难排查。
 *    所以这里绝不能用 `encodeURI`（它不编码 `#`），必须用 `encodeURIComponent`。
 *
 * 2. **SVG 内部统一用双引号，`url()` 外层必须用单引号**。
 *    `encodeURIComponent` 会把 `"` 编码成 `%22`，因此外层用单引号是安全的；
 *    但**两头不能用同一种引号**，否则外层引号会被内层引号提前闭合，
 *    url 被截断成半截字符串，同样只是"图标没了"而没有报错。
 *
 * @param {string} path  ICON_PATHS 里的 `<path>` 片段
 * @param {string} color 描边颜色，如 '#1989fa' 或 COLORS.primary
 * @returns {string} 形如 `data:image/svg+xml,%3Csvg...` 的 data URI
 */
function iconUrl(path, color) {
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" ' +
    'fill="none" stroke="' + color + '" stroke-width="2" ' +
    'stroke-linecap="round" stroke-linejoin="round">' +
    path +
    '</svg>';
  return 'data:image/svg+xml,' + encodeURIComponent(svg);
}

/**
 * 按图标名取图标路径，名字不存在时返回空串（而不是 undefined）。
 *
 * 返回空串之后 {@link iconUrl} 会生成一个"只有 stroke、没有图形"的 SVG，
 * 渲染出来就是一片空白 —— 这是**刻意选择的降级行为**：
 * 少一个图标总比整页白屏好。组件层会另外 `console.warn` 把名字喊出来。
 */
function getPath(name) {
  return ICON_PATHS[name] || '';
}


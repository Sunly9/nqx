-- ============================================================================
-- V17：买家「提醒发货」
-- ============================================================================
-- 【背景】
--
-- 小程序订单页原本有一个「提醒发货」按钮，但它是**假的** —— 点一下只弹一段
-- 「发货说明」的静态文案，不给后端发任何请求，管理员那边也完全不知道。
--
-- 代码里当时留了一段注释解释为什么不调后端：旧版这个按钮直接调
-- `POST /api/procurement/orders/ship`，等于**买家点一下就能把自己的订单
-- 标记成"已发货"**，物流信息完全是假的。那是个更严重的问题，所以先把它
-- 降级成了纯提示。
--
-- 但"什么都不做"也是不对的：买家确实有催发货的诉求，而且管理员完全感知不到。
-- 正确做法是**买家只能"提醒"，发货仍然只能由管理员操作**。
--
-- 【本次改动】
--
-- 给订单表加两列，记录买家的提醒行为：
--   · remind_ship_at    —— 最近一次提醒的时间（用于限频 + 后台展示）
--   · remind_ship_count —— 累计提醒次数（用于后台判断"这单被催了很多次"）
--
-- 限频规则写在业务层（24 小时一次），不放在数据库里 ——
-- 因为规则可能调整，改代码比改表结构容易。
-- ============================================================================

ALTER TABLE `biz_order`
    ADD COLUMN `remind_ship_at`    DATETIME NULL     COMMENT '买家最近一次提醒发货的时间（为空表示从未提醒过）' AFTER `courier_no`,
    ADD COLUMN `remind_ship_count` INT      NOT NULL DEFAULT 0 COMMENT '买家累计提醒发货次数' AFTER `remind_ship_at`;


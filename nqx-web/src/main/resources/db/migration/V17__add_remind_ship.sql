-- 为什么不给 remind_ship_at 单独建索引：
-- 这张表的数据量是校园级（几千行），而筛选条件是 `status = 41 AND remind_ship_at IS NOT NULL`，
-- status 上已有索引，走它之后再过滤即可。单独建索引收益很小却增加写入开销。
